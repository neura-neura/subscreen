 const rows=p.locator('[data-cue-id]');await p.waitForFunction(()=>document.querySelectorAll('textarea').length===3);
 const values=()=>p.locator('textarea').evaluateAll(es=>es.map(e=>e.value));assert.deepEqual(await values(),['One','','Two']);
 const time=await rows.nth(1).getByLabel('IN',{exact:true}).inputValue();
