 assert.equal(await rows.first().getByLabel('IN',{exact:true}).inputValue(),'00:00:00,500');
 assert.equal(await rows.first().getByLabel('OUT',{exact:true}).inputValue(),'00:00:01,000');
 assert.equal(await rows.nth(1).getByLabel('IN',{exact:true}).inputValue(),time);
 await p.keyboard.press('Control+z');assert.deepEqual(await values(),['One','Inserted','Two']);
 await p.keyboard.press('Control+y');assert.deepEqual(await values(),['Inserted','One','Two']);
